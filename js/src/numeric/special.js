/**
 * χ² survival function P[X > x] for df degrees of freedom — scipy.stats.chi2.sf(x, df).
 * chi2Sf(x, df) = Q(df/2, x/2). Negative x gives 1 (scipy: x below the support).
 *
 * @param {number} x
 * @param {number} df > 0
 * @returns {number}
 */
export function chi2Sf(x, df) {
	if (Number.isNaN(x) || Number.isNaN(df) || df <= 0) return NaN;
	if (x <= 0) return 1;
	return gammaincc(df / 2, x / 2);
}

/**
 * χ² cumulative distribution P[X ≤ x] — scipy.stats.chi2.cdf(x, df).
 *
 * @param {number} x
 * @param {number} df > 0
 * @returns {number}
 */
export function chi2Cdf(x, df) {
	if (Number.isNaN(x) || Number.isNaN(df) || df <= 0) return NaN;
	if (x <= 0) return 0;
	return gammaincReg(df / 2, x / 2);
}

/**
 * Student-t survival function P[T > t] — scipy.stats.t.sf(t, df).
 * For t > 0: ½·I_{df/(df+t²)}(df/2, ½); for t < 0: 1 − tSf(−t, df); tSf(0) = ½ exactly.
 *
 * @param {number} t
 * @param {number} df > 0
 * @returns {number}
 */
export function tSf(t, df) {
	if (Number.isNaN(t) || Number.isNaN(df) || df <= 0) return NaN;
	if (t === Infinity) return 0;
	if (t === -Infinity) return 1;
	if (t < 0) return 1 - tSf(-t, df);
	if (t === 0) return 0.5;
	const t2 = t * t;
	const s = df + t2;
	// x = df/(df+t²) and y = t²/(df+t²) are each formed directly (see betaincXY); one route only —
	// an explicit "1 − I_y(½, df/2)" small-t branch was measured to lose 1e-11 relative at t = 5,
	// df = 500 and to underflow to 0 at t = 10, df = 500 (want 6.9e-22), so it was removed.
	return 0.5 * betaincXY(df / 2, 0.5, df / s, t2 / s);
}

/**
 * Student-t cumulative distribution P[T ≤ t] — scipy.stats.t.cdf(t, df); tCdf(t) = tSf(−t).
 *
 * @param {number} t
 * @param {number} df > 0
 * @returns {number}
 */
export function tCdf(t, df) {
	return tSf(-t, df);
}

/**
 * Standard normal survival function P[Z > z] = ½·erfc(z/√2) — scipy.stats.norm.sf(z).
 *
 * @param {number} z
 * @returns {number}
 */
export function normSf(z) {
	return 0.5 * erfc(z / SQRT_2);
}

/**
 * Standard normal cumulative distribution P[Z ≤ z] = ½·erfc(−z/√2) — scipy.stats.norm.cdf(z).
 *
 * @param {number} z
 * @returns {number}
 */
export function normCdf(z) {
	return 0.5 * erfc(-z / SQRT_2);
}


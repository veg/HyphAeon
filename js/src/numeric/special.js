/**
 * ln C(n, k) = lgamma(n+1) − lgamma(k+1) − lgamma(n−k+1). −Infinity when k < 0 or k > n.
 * Real-valued n and k are accepted (the gamma form); the fast exact path is used for integers with
 * min(k, n−k) ≤ 64, where a compensated sum of ln((n−k+i)/i) is accurate to ~1e-15 absolute.
 *
 * @param {number} n ≥ 0
 * @param {number} k
 * @returns {number}
 */
export function logChoose(n, k) {
	if (Number.isNaN(n) || Number.isNaN(k)) return NaN;
	if (k < 0 || k > n) return -Infinity;
	if (Number.isInteger(n) && Number.isInteger(k)) {
		const m = Math.min(k, n - k);
		if (m === 0) return 0;
		if (m <= 64) {
			let sum = 0;
			let comp = 0;
			for (let i = 1; i <= m; i++) {
				const term = Math.log((n - m + i) / i);
				const y = term - comp;
				const t = sum + y;
				comp = t - sum - y;
				sum = t;
			}
			return sum;
		}
	}
	return lgamma(n + 1) - lgamma(k + 1) - lgamma(n - k + 1);
}

/**
 * The hypergeometric support and normalised pmf over it, generated by the ratio recurrence from
 * the mode (see header). `pmf[i]` is P[X = lo + i].
 *
 * pmf(k+1)/pmf(k) = (n − k)(N − k) / ((k + 1)(M − n − N + k + 1)).
 */
function hypergeomTable(M, n, N) {
	const lo = Math.max(0, N - (M - n));
	const hi = Math.min(n, N);
	const size = hi - lo + 1;
	const pmf = new Float64Array(size);
	// Mode: floor((N + 1)(n + 1) / (M + 2)), clamped into the support.
	let mode = Math.floor(((N + 1) * (n + 1)) / (M + 2));
	if (mode < lo) mode = lo;
	if (mode > hi) mode = hi;
	pmf[mode - lo] = 1;
	for (let k = mode; k < hi; k++) {
		const r = ((n - k) * (N - k)) / ((k + 1) * (M - n - N + k + 1));
		pmf[k + 1 - lo] = pmf[k - lo] * r;
	}
	for (let k = mode; k > lo; k--) {
		const r = (k * (M - n - N + k)) / ((n - k + 1) * (N - k + 1));
		pmf[k - 1 - lo] = pmf[k - lo] * r;
	}
	// Normalise; sum smallest-first from each side of the mode for accuracy.
	let total = 0;
	for (let i = 0; i < mode - lo; i++) total += pmf[i];
	let upper = 0;
	for (let i = size - 1; i > mode - lo; i--) upper += pmf[i];
	total += upper + 1;
	for (let i = 0; i < size; i++) pmf[i] /= total;
	return { lo, hi, pmf };
}

function hypergeomArgsValid(M, n, N) {
	return (
		Number.isInteger(M) && Number.isInteger(n) && Number.isInteger(N) && M >= 0 && n >= 0 && n <= M && N >= 0 && N <= M
	);
}

/**
 * Hypergeometric pmf P[X = k] — scipy.stats.hypergeom.pmf(k, M, n, N).
 *
 * @param {number} k successes drawn
 * @param {number} M population size
 * @param {number} n success states in the population
 * @param {number} N draws
 * @returns {number}
 */
export function hypergeomPmf(k, M, n, N) {
	if (!hypergeomArgsValid(M, n, N) || Number.isNaN(k)) return NaN;
	if (!Number.isInteger(k)) return 0;
	const { lo, hi, pmf } = hypergeomTable(M, n, N);
	if (k < lo || k > hi) return 0;
	return pmf[k - lo];
}

/**
 * Hypergeometric cdf P[X ≤ k] — scipy.stats.hypergeom.cdf(k, M, n, N). Non-integer k inside the
 * support gives NaN (scipy 1.16 behaviour, see header).
 *
 * @param {number} k
 * @param {number} M population size
 * @param {number} n success states
 * @param {number} N draws
 * @returns {number}
 */
export function hypergeomCdf(k, M, n, N) {
	if (!hypergeomArgsValid(M, n, N) || Number.isNaN(k)) return NaN;
	const { lo, hi, pmf } = hypergeomTable(M, n, N);
	if (k < lo) return 0;
	if (k >= hi) return 1;
	if (!Number.isInteger(k)) return NaN;
	let s = 0;
	for (let i = 0; i <= k - lo; i++) s += pmf[i];
	return s;
}

/**
 * Hypergeometric survival P[X > k] — scipy.stats.hypergeom.sf(k, M, n, N). Non-integer k inside
 * the support gives NaN (scipy 1.16 behaviour, see header).
 *
 * @param {number} k
 * @param {number} M population size
 * @param {number} n success states
 * @param {number} N draws
 * @returns {number}
 */
export function hypergeomSf(k, M, n, N) {
	if (!hypergeomArgsValid(M, n, N) || Number.isNaN(k)) return NaN;
	const { lo, hi, pmf } = hypergeomTable(M, n, N);
	if (k < lo) return 1;
	if (k >= hi) return 0;
	if (!Number.isInteger(k)) return NaN;
	let s = 0;
	for (let i = pmf.length - 1; i > k - lo; i--) s += pmf[i];
	return s;
}

	BUSTED_LRT_THRESHOLD,
	BUSTED_EMBED_DIM,
	BUSTED_HEAD_INPUT_NAMES,
	BUSTED_HEAD_OUTPUT_NAMES,
	variableSiteIndices,
	totalSelectionEnergy,

/**
 * omnibus.test.js — the BUSTED statistical bridge of cli.py cmd_busted (src/omnibus.js).
 *
 * WHY THIS FILE EXISTS
 *
 * Three oracles, from strongest to weakest:
 *   1. fixtures/e2e/busted_Smc6.json and busted_HIV1_RT.json — the CLI's own JSON. They carry the
 *      aggregate statistics but NOT the per-site LRTs they were computed from; those are taken from
 *      fixtures/e2e/meme_Smc6.json / meme_HIV1_RT.json, whose `sites[].hyphaeon_lrt` the same
 *      model produced on the same taxa (cmd_meme and cmd_busted both run `forward_cached` on the
 *      variable sites and clamp at 0). That the meme LRTs reproduce every busted statistic bit for
 *      bit was verified with the reference Python before this test was written, so the replay is a
 *      test of the JS arithmetic, not of that assumption. The neural-head fields are null in the
 *      fixtures (the reference head is non-deterministic, fixtures/README.md) and are asserted
 *      null here.
 *   2. test/data/omnibus/busted_stats.json — the same cli.py lines on seeded random and edge-case
 *      inputs (no variable sites, one site, LRTs at the 3.841 threshold, huge LRTs, ties,
 *      denormals), generated by test/data/omnibus/gen.py with numpy 2.3.3.
 *   3. Hand-checkable unit cases for each exported function, and a fake-model exercise of
 *      `runBusted` that pins the loop's contract: variable sites only, ascending, batched, clamped,
 *      `hidden_all` zero at invariable sites, an all-false mask to the head.
 *
 * TOLERANCES. The float32 sums (`total_selection_energy`, `omnibus_lrt`) are asserted EQUAL: the
 * reference is a float32 pairwise reduction and omnibus.js reproduces it (a float64 sum is shown to
 * miss by ~6e-6, which the fixture's 1e-5 class would hide). The float64 p-values are asserted to
 * 1e-12 (fixture class 1e-9 for float64 statistics); counts exactly.
 */
